    if (s.pickClass) extra.cls = nearestSeenClass();
    if (s.pickSchool) extra.school = "ogien";
    send({
      t: "cast", spell: e.id, ax: lastAim.x, ay: lastAim.y,
      d: aimRatio, cls: extra.cls, school: extra.school
    });
