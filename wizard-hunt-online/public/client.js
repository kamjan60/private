  /**
   * One frame of a school's impact sheet, centred on a world point.
   *
   * Returns false when that school has no sheet, so the caller can fall back
   * rather than silently drawing nothing.
   */
  function drawFxFrame(school, x, y, elapsed, scale) {
    var d = FXDEF[school], im = IMG[school];
    if (!d || !im || !im.complete || !im.naturalWidth) return false;
    var fw = d[0], fh = d[1], n = d[2], ms = d[3];
    var i = Math.floor(elapsed / ms) % n;
    var w = fw * (scale || 1), h = fh * (scale || 1);
    ctx.drawImage(im, i * fw, 0, fw, fh, Math.round(x - w / 2), Math.round(y - h / 2), w, h);
    return true;
  }

  /**
   * A zone's floor, tiled once and cached.
   *
   * Tiling live would be several thousand drawImage calls a frame; one
   * cached bitmap per zone is one call. The variant is chosen from the
   * tile's own coordinates so a room looks worked-in without anybody
   * authoring a map, and looks the same every time it is drawn.
   */
  /** A stable stream of numbers from a room's own name. */
  function seedOf(name) {
    var h = 2166136261;
    for (var i = 0; i < name.length; i++) {
      h ^= name.charCodeAt(i); h = (h * 16777619) >>> 0;
    }
    return function () { h = (1103515245 * h + 12345) & 0x7fffffff; return h / 0x7fffffff; };
  }

  function floorFor(z) {
    if (floorCache[z.name] !== undefined) return floorCache[z.name];
    var t = IMG.tiles, pr = IMG.props;
    if (!t.complete || !t.naturalWidth) return null;   // retry next frame
    if (!pr.complete || !pr.naturalWidth) return null;

    var wl = IMG.walls;
    if (!wl.complete || !wl.naturalWidth) return null;

    // The canvas is grown by a margin on every side: a wall sits ON the
    // zone's boundary, so half of it would fall outside a canvas cut to the
    // zone exactly. Everything inside is offset by the same margin.
    var M = WALL_M;
    var cvs = document.createElement("canvas");
    cvs.width = z.w + M * 2; cvs.height = z.h + M * 2;
    var g = cvs.getContext("2d");
    g.translate(M, M);
    var hall = z.kind === "corridor";
    var cols = Math.ceil(z.w / TILE), rows = Math.ceil(z.h / TILE);

    for (var ty = 0; ty < rows; ty++) {
      for (var tx = 0; tx < cols; tx++) {
        var hsh = ((tx * 73856093) ^ (ty * 19349663) ^ z.name.length * 83492791) >>> 0;
        var idx;
        if (hall) {
          // Chevrons only on the first and last tile ALONG the corridor. A
          // corridor is barely four tiles long, so "touches any edge" paints
          // the whole thing yellow.
          var along = z.w > z.h ? tx : ty;
          var last = (z.w > z.h ? cols : rows) - 1;
          idx = (along === 0 || along === last) ? 5 : 3 + (hsh % 2);
        } else {
          idx = hsh % 16 === 0 ? 6 : hsh % 23 === 0 ? 7 : hsh % 3;
        }
        g.drawImage(t, idx * TILE, 0, TILE, TILE, tx * TILE, ty * TILE, TILE, TILE);
      }
    }

    // ---------------------------------------------------------- furniture
    var rnd = seedOf(z.name);
    var kit = (hall ? HALL_KIT : ROOM_KIT[z.name] || [2, 3]).slice();

    // Cells along the walls, one tile in. Furniture belongs against a wall:
    // filling the middle would leave nowhere to walk and nowhere to fight.
    var cells = [];
    for (var x = 1; x < cols - 1; x++) { cells.push([x, 0]); cells.push([x, rows - 1]); }
    for (var y = 1; y < rows - 1; y++) { cells.push([0, y]); cells.push([cols - 1, y]); }
    if (!cells.length) cells.push([0, 0]);
    for (var i = cells.length - 1; i > 0; i--) {
      var j = Math.floor(rnd() * (i + 1));
      var tmp = cells[i]; cells[i] = cells[j]; cells[j] = tmp;
    }

    var placed = [];
    for (var k = 0; k < kit.length && k < cells.length; k++) {
      placed.push({ prop: kit[k], cx: cells[k][0] * TILE, cy: cells[k][1] * TILE });
    }

    // ---------------------------------------------------------- lighting
    // Some rooms keep a working fixture, some do not. A wreck where every
    // room is evenly lit is not a wreck; a wreck where none are is unplayable.
    var lamps = hall ? (rnd() < 0.45 ? 1 : 0) : Math.floor(rnd() * 3);
    for (var l = 0; l < lamps && cells.length > kit.length + l; l++) {
      var c = cells[kit.length + l];
      placed.push({ prop: LAMP, cx: c[0] * TILE, cy: c[1] * TILE });
    }

    // darken everything, then cut the light back in only where something is
    // actually emitting
    g.fillStyle = "rgba(3,5,10,0.40)";
    g.fillRect(0, 0, z.w, z.h);

    g.globalCompositeOperation = "lighter";
    placed.forEach(function (o) {
      var kind = EMITTERS[o.prop];
      if (!kind) return;
      var lx = o.cx + TILE / 2, ly = o.cy + TILE / 2;
      var R = o.prop === LAMP ? 118 : 78;
      var grad = g.createRadialGradient(lx, ly, 2, lx, ly, R);
      if (kind === "warm") {
        grad.addColorStop(0, "rgba(255,196,110,0.62)");
        grad.addColorStop(0.45, "rgba(190,140,76,0.26)");
        grad.addColorStop(1, "rgba(0,0,0,0)");
      } else {
        grad.addColorStop(0, "rgba(120,200,255,0.5)");
        grad.addColorStop(0.45, "rgba(70,135,185,0.2)");
        grad.addColorStop(1, "rgba(0,0,0,0)");
      }
      g.fillStyle = grad;
      g.fillRect(lx - R, ly - R, R * 2, R * 2);
    });
    g.globalCompositeOperation = "source-over";

    // Only the dead fittings are baked. Anything with a light on it is drawn
    // live every frame instead: a console whose indicators never move reads
    // as a sticker, not as equipment that is somehow still running.
    placed.forEach(function (o) {
      if (EMITTERS[o.prop]) return;
      g.drawImage(pr, o.prop * TILE, 0, TILE, TILE, o.cx, o.cy, TILE, TILE);
    });
    emitCache[z.name] = placed
      .filter(function (o) { return !!EMITTERS[o.prop]; })
      .map(function (o) { return { prop: o.prop, x: z.x + o.cx, y: z.y + o.cy }; });

    // ---------------------------------------------------------- bulkheads
    // Stamped along the segments the server sent, which already have the
    // doorways cut out of them, so an opening is simply a stretch with no
    // wall stamped over it.
    // Which side of this wall faces nothing? A viewport is only honest where
    // there is genuinely open space beyond it, so the far side is sampled
    // against the zone list rather than guessed from the room's position.
    function openBeyond(wx, wy, nx, ny) {
      var px = wx + nx * 40, py = wy + ny * 40;
      for (var i = 0; i < DEF.map.length; i++) {
        var o = DEF.map[i];
        if (px >= o.x && px <= o.x + o.w && py >= o.y && py <= o.y + o.h) return false;
      }
      return true;
    }

    var wrnd = seedOf(z.name + "|walls");
    z.walls.forEach(function (w, wi) {
      var x1 = w.x1 - z.x, y1 = w.y1 - z.y, x2 = w.x2 - z.x, y2 = w.y2 - z.y;
      var horiz = y1 === y2;
      // outward normal: away from the middle of the zone
      var nx = horiz ? 0 : (x1 < z.w / 2 ? -1 : 1);
      var ny = horiz ? (y1 < z.h / 2 ? -1 : 1) : 0;

      var from = horiz ? x1 : y1, to = horiz ? x2 : y2;
      for (var a = from; a < to; a += WALL_L) {
        var run = Math.min(WALL_L, to - a);
        var feat = WALL_PLAIN;
        // a partial run would cut a fitting in half, so those stay plain
        if (run === WALL_L) {
          var r = wrnd();
          if (r > 0.62) {
            var midX = z.x + (horiz ? a + WALL_L / 2 : x1);
            var midY = z.y + (horiz ? y1 : a + WALL_L / 2);
            var canWindow = openBeyond(midX, midY, nx, ny);
            var pool = canWindow ? WALL_INNER.concat([WALL_VIEWPORT]) : WALL_INNER;
            feat = pool[Math.floor(wrnd() * pool.length) % pool.length];
          }
        }
        var src = horiz ? wallH(feat) : wallV(feat);
        if (horiz) {
          g.drawImage(wl, src[0], src[1], run, src[3], a, y1 - WALL_TH / 2, run, src[3]);
        } else {
          g.drawImage(wl, src[0], src[1], src[2], run, x1 - WALL_TH / 2, a, src[2], run);
        }
      }
    });
    [[0, 0], [z.w, 0], [0, z.h], [z.w, z.h]].forEach(function (c) {
      g.drawImage(wl, WALL_C[0], WALL_C[1], WALL_C[2], WALL_C[3],
        c[0] - WALL_TH / 2, c[1] - WALL_TH / 2, WALL_C[2], WALL_C[3]);
    });

    floorCache[z.name] = cvs;
    return cvs;
  }

  function drawActor(a, alpha) {
    // Cień: your own body goes see-through, because otherwise the only way to
    // tell whether the spell is still up is to be shot at.
    var fade = a.invisible ? 0.34 : (alpha === undefined ? 1 : alpha);
    var prev = ctx.globalAlpha;
    if (fade !== 1) ctx.globalAlpha = prev * fade;
    if (!drawSprite(a.cls, a.it, a.dir, a.step,
        Math.round(a.x) - 16, Math.round(a.y) - 24, 32, 32)) {
      ctx.fillStyle = "#8b9ac0";
      ctx.fillRect(a.x - 8, a.y - 16, 16, 24);
    }
    if (a.casting) {
      ctx.strokeStyle = "#c682ff"; ctx.lineWidth = 2;
      ctx.beginPath(); ctx.arc(a.x, a.y - 6, 20 + Math.sin(Date.now() / 90) * 3, 0, 6.284); ctx.stroke();
    }
    if (a.stunned) {
      ctx.fillStyle = "#ffc35c"; ctx.font = "12px system-ui";
      ctx.fillText("!", a.x - 2, a.y - 26);
    }
    if (a.channel) {
      ctx.fillStyle = "rgba(127,216,255,0.85)";
      ctx.fillRect(a.x - 12, a.y + 12, 24, 3);
    }
    ctx.fillStyle = a.id === (S.me && S.me.id) ? "#7fd8ff" : "rgba(200,214,240,0.75)";
    ctx.font = "10px system-ui";
    // stagger by id: bodies pile up constantly in this game and two labels
    // at the same height read as one nonsense word
    var lift = 28 + (parseInt(String(a.id).replace(/\D/g, ""), 10) % 3) * 9;
    ctx.fillText(a.name, a.x - ctx.measureText(a.name).width / 2, a.y - lift);

    if (a.invisible) {
      ctx.fillStyle = "#c682ff";
      ctx.font = "9px system-ui";
      ctx.fillText("CIEŃ", a.x - 11, a.y + 22);
    }
    ctx.globalAlpha = prev;
  }

  /**
   * Nothing renders until the manifest is in hand.
   *
   * Starting the loop first and letting sprites appear once the manifest
   * lands would mean a frame of fallback bodies -- which is precisely the
   * "wrong body, no error" failure this feature exists to remove, just
   * shorter. So the loop starts here or not at all, and a manifest that will
   * not load says so on the screen instead of in the console.
   */
  function boot() {
    requestAnimationFrame(draw);
  }

  function fatal(why) {
    // the entry screen's own error line, and the join button disabled: the
    // game is unplayable without sprites, so let nobody start a round that
    // would render nothing
    var el = $("err");
    if (el) el.textContent = why;
    var join = $("btnJoin");
    if (join) join.disabled = true;
    console.error(why);
  }

